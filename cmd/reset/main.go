// Reset generates Reset methods for structs marked with the comment
// "// generate:reset".
//
// It loads every package under the given directory (the current one by
// default) and writes the methods of each package to reset.gen.go next to
// its sources:
//
//	go run ./cmd/reset
//	make generate
//
// Reset sets the fields to their initial values:
//
//   - numbers, strings and bools get their zero values;
//   - slices are cut to zero length, the capacity is kept;
//   - maps are cleared;
//   - fields whose type has a Reset() method call it;
//   - non-nil pointers are reset by the same rules;
//   - other fields (arrays, structs without Reset, interfaces, channels,
//     functions) get their zero values.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"io/fs"
	"log"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"text/template"

	"golang.org/x/tools/go/packages"
)

const (
	marker  = "generate:reset"
	genFile = "reset.gen.go"
)

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}

	if err := run(root); err != nil {
		log.Fatal(err)
	}
}

// run writes reset.gen.go for every package under root that has marked
// structs.
func run(root string) error {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo,
		Dir: root,
	}
	// Package errors are not checked: a stale reset.gen.go or a call to a
	// Reset that is not generated yet break only function bodies, the struct
	// types are still known.
	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return err
	}
	if len(pkgs) == 0 {
		return fmt.Errorf("no packages found in %s", root)
	}

	// Find the structs of all packages first: a field may have a marked type
	// from another package whose Reset is not generated yet.
	structs := make(map[*packages.Package][]*types.Named)
	marked := make(map[string]bool)
	for _, pkg := range pkgs {
		for _, named := range findStructs(pkg) {
			structs[pkg] = append(structs[pkg], named)
			marked[types.TypeString(named, nil)] = true
		}
	}

	for _, pkg := range pkgs {
		if len(pkg.GoFiles) == 0 {
			continue
		}
		path := filepath.Join(filepath.Dir(pkg.GoFiles[0]), genFile)

		if len(structs[pkg]) == 0 {
			// The package has no marked structs anymore.
			if err := os.Remove(path); err != nil && !errors.Is(err, fs.ErrNotExist) {
				return err
			}
			continue
		}

		src, err := generate(pkg.Types, structs[pkg], marked)
		if err != nil {
			return fmt.Errorf("%s: %w", pkg.PkgPath, err)
		}
		if err := os.WriteFile(path, src, 0o644); err != nil {
			return err
		}
	}

	return nil
}

// findStructs returns the structs of pkg marked with the generate:reset
// comment.
func findStructs(pkg *packages.Package) []*types.Named {
	var result []*types.Named
	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}

			for _, spec := range gen.Specs {
				ts := spec.(*ast.TypeSpec)
				// The comment of a single type belongs to the declaration,
				// of a type inside type ( ... ) to the spec.
				if !hasMarker(gen.Doc) && !hasMarker(ts.Doc) {
					continue
				}

				if named := structType(pkg, ts); named != nil {
					result = append(result, named)
				} else {
					log.Printf("%s: skip %s: only non-generic structs are supported", pkg.PkgPath, ts.Name.Name)
				}
			}
		}
	}

	return result
}

// structType returns the type declared by ts if it is a non-generic struct.
func structType(pkg *packages.Package, ts *ast.TypeSpec) *types.Named {
	obj, ok := pkg.TypesInfo.Defs[ts.Name].(*types.TypeName)
	if !ok {
		return nil
	}
	named, ok := obj.Type().(*types.Named)
	if !ok || named.TypeParams().Len() > 0 {
		return nil
	}
	if _, ok := named.Underlying().(*types.Struct); !ok {
		return nil
	}
	return named
}

func hasMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == marker {
			return true
		}
	}
	return false
}

// fileTmpl is the layout of reset.gen.go. The statements that reset the
// fields are built by generator.reset, gofmt fixes their indentation.
var fileTmpl = template.Must(template.New(genFile).Parse(`// Code generated by cmd/reset; DO NOT EDIT.

package {{.Package}}
{{with .Imports}}
import (
{{- range .}}
	{{printf "%q" .}}
{{- end}}
)
{{end}}
{{- range .Methods}}
// Reset resets the fields of {{.Type}} to their initial values.
func ({{.Recv}} *{{.Type}}) Reset() {
	if {{.Recv}} == nil {
		return
	}
{{range .Fields}}
	{{.}}
{{- end}}
}
{{end}}`))

// fileData is the data for fileTmpl.
type fileData struct {
	Package string
	Imports []string
	Methods []methodData
}

// methodData is the Reset method of one struct.
type methodData struct {
	Type   string
	Recv   string
	Fields []string // statements that reset the fields
}

// generator builds the Reset methods of one package.
type generator struct {
	pkg     *types.Package
	marked  map[string]bool // structs that get Reset in this run
	imports map[string]bool // packages used by the generated code
}

// generate returns the formatted source of reset.gen.go for pkg.
func generate(pkg *types.Package, structs []*types.Named, marked map[string]bool) ([]byte, error) {
	g := &generator{pkg: pkg, marked: marked, imports: make(map[string]bool)}

	data := fileData{Package: pkg.Name()}
	for _, named := range structs {
		data.Methods = append(data.Methods, g.method(named))
	}
	// The imports are known only after the methods are built.
	data.Imports = slices.Sorted(maps.Keys(g.imports))

	var src bytes.Buffer
	if err := fileTmpl.Execute(&src, data); err != nil {
		return nil, err
	}
	return format.Source(src.Bytes())
}

// method returns the Reset method of a struct.
func (g *generator) method(named *types.Named) methodData {
	m := methodData{Type: named.Obj().Name(), Recv: receiverName(named)}

	st := named.Underlying().(*types.Struct)
	for i := range st.NumFields() {
		field := st.Field(i)
		if field.Name() == "_" {
			continue
		}
		m.Fields = append(m.Fields, g.reset(m.Recv+"."+field.Name(), field.Type()))
	}

	return m
}

// reset returns the statement that resets expr of type t.
func (g *generator) reset(expr string, t types.Type) string {
	if g.hasReset(t) {
		return paren(expr) + ".Reset()"
	}

	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Info()&types.IsBoolean != 0:
			return expr + " = false"
		case u.Info()&types.IsString != 0:
			return expr + ` = ""`
		case u.Info()&types.IsNumeric != 0:
			return expr + " = 0"
		default: // unsafe.Pointer
			return expr + " = nil"
		}
	case *types.Slice:
		return fmt.Sprintf("%s = %s[:0]", expr, paren(expr))
	case *types.Map:
		return fmt.Sprintf("clear(%s)", expr)
	case *types.Pointer:
		inner := paren(expr) + ".Reset()"
		if !g.hasReset(u.Elem()) {
			inner = g.reset("*"+expr, u.Elem())
		}
		return fmt.Sprintf("if %s != nil {\n%s\n}", expr, inner)
	case *types.Struct, *types.Array:
		return fmt.Sprintf("%s = %s{}", expr, types.TypeString(t, g.qualifier))
	default: // interfaces, channels, functions
		return expr + " = nil"
	}
}

// hasReset reports whether t has a Reset() method or gets it in this run.
// Pointers and interfaces are excluded: they may be nil.
func (g *generator) hasReset(t types.Type) bool {
	switch t.Underlying().(type) {
	case *types.Pointer, *types.Interface:
		return false
	}
	if g.marked[types.TypeString(t, nil)] {
		return true
	}

	obj, _, _ := types.LookupFieldOrMethod(t, true, nil, "Reset")
	fn, ok := obj.(*types.Func)
	return ok && fn.Signature().Params().Len() == 0
}

// qualifier returns the name of package p in the generated code and adds p
// to the imports.
func (g *generator) qualifier(p *types.Package) string {
	if p == g.pkg {
		return ""
	}
	g.imports[p.Path()] = true
	return p.Name()
}

// receiverName returns the receiver name of the other methods of the type,
// so that all of them are named the same, or the first letter of the type.
func receiverName(named *types.Named) string {
	for i := range named.NumMethods() {
		m := named.Method(i)
		if name := m.Signature().Recv().Name(); m.Name() != "Reset" && name != "" && name != "_" {
			return name
		}
	}
	return strings.ToLower(named.Obj().Name()[:1])
}

// paren wraps a dereference in parentheses, so *p can be followed by a
// selector or a slice expression.
func paren(expr string) string {
	if strings.HasPrefix(expr, "*") {
		return "(" + expr + ")"
	}
	return expr
}
