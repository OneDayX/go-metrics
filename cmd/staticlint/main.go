// otherChecks are the checks taken from the staticcheck classes other than
// SA: S (simple), ST (stylecheck) and QF (quickfix).
var otherChecks = map[string]bool{
	"S1002":  true,
	"S1008":  true,
	"S1039":  true,
	"ST1005": true,
	"ST1016": true,
	"ST1019": true,
	"QF1003": true,
}

func main() {
	multichecker.Main(analyzers()...)
}

// analyzers returns every check of staticlint, see the package documentation.
func analyzers() []*analysis.Analyzer {
	checks := []*analysis.Analyzer{
		// golang.org/x/tools/go/analysis/passes
		appends.Analyzer,
		asmdecl.Analyzer,
		assign.Analyzer,
		atomic.Analyzer,
		atomicalign.Analyzer,
		bools.Analyzer,
		buildtag.Analyzer,
		cgocall.Analyzer,
		composite.Analyzer,
		copylock.Analyzer,
		deepequalerrors.Analyzer,
		defers.Analyzer,
		directive.Analyzer,
		errorsas.Analyzer,
		framepointer.Analyzer,
		gofix.Analyzer,
		hostport.Analyzer,
		httpmux.Analyzer,
		httpresponse.Analyzer,
		ifaceassert.Analyzer,
		inline.Analyzer,
		loopclosure.Analyzer,
		lostcancel.Analyzer,
		nilfunc.Analyzer,
		nilness.Analyzer,
		printf.Analyzer,
		reflectvaluecompare.Analyzer,
		scannererr.Analyzer,
		shift.Analyzer,
		sigchanyzer.Analyzer,
		slog.Analyzer,
		sortslice.Analyzer,
		sqlrowserr.Analyzer,
		stdmethods.Analyzer,
		stdversion.Analyzer,
		stringintconv.Analyzer,
		structtag.Analyzer,
		testinggoroutine.Analyzer,
		tests.Analyzer,
		timeformat.Analyzer,
		unmarshal.Analyzer,
		unreachable.Analyzer,
		unsafeptr.Analyzer,
		unusedresult.Analyzer,
		unusedwrite.Analyzer,
		waitgroup.Analyzer,

		// Public analyzers.
		errcheck.Analyzer,
		bodyclose.Analyzer,

		// Our own analyzer.
		osexit.Analyzer,
	}

	// The staticcheck package holds exactly the SA class, all of it is used.
	for _, a := range staticcheck.Analyzers {
		checks = append(checks, a.Analyzer)
	}

	for _, set := range [][]*lint.Analyzer{simple.Analyzers, stylecheck.Analyzers, quickfix.Analyzers} {
		for _, a := range set {
			if otherChecks[a.Analyzer.Name] {
				checks = append(checks, a.Analyzer)
			}
		}
	}

	return checks
}
